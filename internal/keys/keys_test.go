func TestPlaceholderValues(t *testing.T) {
	h := sha256.Sum256([]byte("local-plaintext-xci-header-placeholder"))
	if got := hex.EncodeToString(h[:]); got != HeaderKeyValue {
		t.Errorf("HeaderKeyValue = %s, want %s", got, HeaderKeyValue)
	}
	m := md5.Sum([]byte("local-plaintext-xci-area-placeholder"))
	if got := hex.EncodeToString(m[:]); got != KeyAreaKeyApplication00Value {
		t.Errorf("KeyAreaKeyApplication00Value = %s, want %s", got, KeyAreaKeyApplication00Value)
	}
}

func TestPlaceholderText(t *testing.T) {
	want := "# Local placeholders for unsigned plaintext repacks; NOT Nintendo keys.\n" +
		"# Cannot decrypt retail content. Keep real keys in prod.keys.\n" +
		"header_key = " + HeaderKeyValue + "\n" +
		"key_area_key_application_00 = " + KeyAreaKeyApplication00Value + "\n"
	if got := PlaceholderText(nil); got != want {
		t.Errorf("PlaceholderText(nil) = %q, want %q", got, want)
	}

	wantSub := "# Local placeholders for unsigned plaintext repacks; NOT Nintendo keys.\n" +
		"# Cannot decrypt retail content. Keep real keys in prod.keys.\n" +
		"key_area_key_application_00 = " + KeyAreaKeyApplication00Value + "\n"
	if got := PlaceholderText([]string{KeyAreaKeyApplication00}); got != wantSub {
		t.Errorf("PlaceholderText([area]) = %q, want %q", got, wantSub)
	}
}

func TestInspectStates(t *testing.T) {
	dir := t.TempDir()

	st, err := Inspect(dir)
	if err != nil {
		t.Fatalf("Inspect: %v", err)
	}
	if st.Ready {
		t.Fatal("empty dir should not be ready")
	}
	if len(st.Missing) != 2 || st.Missing[0] != HeaderKey || st.Missing[1] != KeyAreaKeyApplication00 {
		t.Errorf("Missing = %v", st.Missing)
	}
	if len(st.Invalid) != 0 {
		t.Errorf("Invalid = %v", st.Invalid)
	}

	if err := os.WriteFile(filepath.Join(dir, "prod.keys"), []byte("header_key = abc\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	st, err = Inspect(dir)
	if err != nil {
		t.Fatalf("Inspect: %v", err)
	}
	if st.Ready {
		t.Fatal("should not be ready with an invalid entry")
	}
	if len(st.Missing) != 1 || st.Missing[0] != KeyAreaKeyApplication00 {
		t.Errorf("Missing = %v", st.Missing)
	}
	if len(st.Invalid) != 1 || st.Invalid[0] != HeaderKey {
		t.Errorf("Invalid = %v", st.Invalid)
	}

	content := "header_key = " + HeaderKeyValue + "\nkey_area_key_application_00 = " + KeyAreaKeyApplication00Value + "\n"
	if err := os.WriteFile(filepath.Join(dir, "prod.keys"), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	st, err = Inspect(dir)
	if err != nil {
		t.Fatalf("Inspect: %v", err)
	}
	if !st.Ready {
		t.Fatal("should be ready with both valid entries")
	}
	if len(st.Missing) != 0 || len(st.Invalid) != 0 {
		t.Errorf("Missing=%v Invalid=%v", st.Missing, st.Invalid)
	}
}

func TestInspectSymlink(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("skipping symlink test as root")
	}
	dir := t.TempDir()
	if err := os.Symlink("/etc/hosts", filepath.Join(dir, "prod.keys")); err != nil {
		t.Skipf("cannot create symlink: %v", err)
	}
	if _, err := Inspect(dir); err == nil {
		t.Fatal("expected symlink refusal from Inspect")
	}
}

func TestInspectTooLarge(t *testing.T) {
	dir := t.TempDir()
	f, err := os.Create(filepath.Join(dir, "prod.keys"))
	if err != nil {
		t.Fatal(err)
	}
	if err := f.Truncate(8*1024*1024 + 1); err != nil {
		t.Fatal(err)
	}
	f.Close()
	if _, err := Inspect(dir); err == nil || err.Error() != "Key configuration file is unexpectedly large." {
		t.Fatalf("err = %v", err)
	}
}

func TestInstall(t *testing.T) {
	dir := t.TempDir()
	res, err := Install(dir)
	if err != nil {
		t.Fatalf("Install: %v", err)
	}
	if !res.Ready {
		t.Fatal("should be ready after install")
	}
	if len(res.Added) != 2 {
		t.Errorf("Added = %v", res.Added)
	}
	if res.Backup != "" {
		t.Errorf("Backup = %q, want empty", res.Backup)
	}
	data, err := os.ReadFile(filepath.Join(dir, "prod.keys_autogenerated"))
	if err != nil {
		t.Fatal(err)
	}
	if string(data) != PlaceholderText(nil) {
		t.Errorf("file content = %q, want placeholder block", data)
	}

	// Idempotent: second install adds nothing and leaves the file untouched.
	res2, err := Install(dir)
	if err != nil {
		t.Fatalf("Install (idempotent): %v", err)
	}
	if !res2.Ready || len(res2.Added) != 0 || res2.Backup != "" {
		t.Errorf("idempotent result = %+v", res2)
	}
	data2, err := os.ReadFile(filepath.Join(dir, "prod.keys_autogenerated"))
	if err != nil {
		t.Fatal(err)
	}
	if string(data2) != string(data) {
		t.Error("file changed on idempotent install")
	}
}

func TestInstallBackup(t *testing.T) {
	dir := t.TempDir()
	before := []byte("header_key = " + HeaderKeyValue + "\n")
	if err := os.WriteFile(filepath.Join(dir, "prod.keys_autogenerated"), before, 0o644); err != nil {
		t.Fatal(err)
	}

	res, err := Install(dir)
	if err != nil {
		t.Fatalf("Install: %v", err)
	}
	if !res.Ready {
		t.Fatal("should be ready after install")
	}
	if len(res.Added) != 1 || res.Added[0] != KeyAreaKeyApplication00 {
		t.Errorf("Added = %v", res.Added)
	}
	if res.Backup == "" {
		t.Fatal("expected a backup path")
	}
	backupData, err := os.ReadFile(res.Backup)
	if err != nil {
		t.Fatal(err)
	}
	if string(backupData) != string(before) {
		t.Errorf("backup = %q, want %q", backupData, before)
	}
	base := filepath.Base(res.Backup)
	if !regexp.MustCompile(`^prod\.keys_autogenerated\.packager-backup-\d{8}-\d{6}-\d{6}$`).MatchString(base) {
		t.Errorf("backup filename = %q", base)
	}

	target, err := os.ReadFile(filepath.Join(dir, "prod.keys_autogenerated"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(target), "header_key = "+HeaderKeyValue) {
		t.Errorf("existing entry not preserved:\n%s", target)
	}
	if !strings.Contains(string(target), KeyAreaKeyApplication00+" = "+KeyAreaKeyApplication00Value) {
		t.Errorf("missing entry not added:\n%s", target)
	}
}

func TestInstallInvalidErrors(t *testing.T) {
	dir := t.TempDir()
	original := "header_key = short\n"
	if err := os.WriteFile(filepath.Join(dir, "prod.keys_autogenerated"), []byte(original), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Install(dir); err == nil {
		t.Fatal("expected error for invalid entry")
	} else if !strings.Contains(err.Error(), "Existing entries need manual correction") {
		t.Errorf("err = %v", err)
	}
	data, err := os.ReadFile(filepath.Join(dir, "prod.keys_autogenerated"))
	if err != nil {
		t.Fatal(err)
	}
	if string(data) != original {
		t.Errorf("file was modified despite error: %q", data)
	}
}
